// Builds dist/itch for itch.io: game.js + fin.js bundled into one private scope (so page add-ons
// that declare globals like `$` or `t` can't clash with the game), plus index.html and assets/.
// The game switches to the coin store by itself on itch.io hosts (see COIN_STORE in game.js).
// Usage: node build-itch.js && butler push dist/itch agonygames/brainrot-battle:html5 --userversion X.Y.Z
const fs = require('fs'), path = require('path');
const root = __dirname, out = path.join(root, 'dist', 'itch');
fs.rmSync(out, { recursive: true, force: true });
fs.mkdirSync(out, { recursive: true });
const read = f => fs.readFileSync(path.join(root, f), 'utf8');
const bundle = '// Generated by build-itch.js from game.js + fin.js. Do not edit.\n(function(){\n' + read('game.js') + '\n;\n' + read('fin.js') + '\n})();\n';
fs.writeFileSync(path.join(out, 'brainrot.js'), bundle);
let html = read('index.html');
const tags = ['<script src="game.js"></script>', '<script src="fin.js"></script>'];
for (const t of tags) if (!html.includes(t)) throw new Error('missing ' + t);
html = html.replace(tags[0], '<script src="brainrot.js"></script>').replace(tags[1], '');
fs.writeFileSync(path.join(out, 'index.html'), html);
fs.cpSync(path.join(root, 'assets'), path.join(out, 'assets'), { recursive: true });
console.log('dist/itch ready:', fs.readdirSync(out).join(', '));
